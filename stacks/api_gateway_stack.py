"""
API Gateway Stack for Strava AI Boost

This stack creates the REST API endpoints for the local web interface:
- Configuration endpoints for OAuth and module management
- Dashboard endpoints for statistics and monitoring
- Status endpoints for real-time processing updates
"""

import os

from aws_cdk import (
    Aws,
    Stack,
    aws_apigateway as apigateway,
    aws_cloudwatch as cloudwatch,
    aws_cloudwatch_actions as cw_actions,
    aws_lambda as lambda_,
    aws_iam as iam,
    aws_cognito as cognito,
    aws_sns as sns,
    Duration,
    CfnOutput
)
from constructs import Construct
from .api_logging import api_stage_logging_options
from .core_infrastructure_stack import CoreInfrastructureStack


FEEDBACK_POST_THROTTLE_RATE_LIMIT = 5
FEEDBACK_POST_THROTTLE_BURST_LIMIT = 10
OPS_ALERTS_TOPIC_NAME = "strava-ai-boost-ops-alerts"


class ApiGatewayStack(Stack):
    """API Gateway stack for local web interface"""

    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        core_stack: CoreInfrastructureStack,
        webhook_stack=None,
        step_functions_arn: str = None,
        user_pool=None,
        user_pool_client=None,
        cloudfront_domain: str = None,
        audio_debrief_lambda: lambda_.IFunction = None,
        push_api_lambda: lambda_.IFunction = None,
        **kwargs
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)

        self.core_stack = core_stack
        self.webhook_stack = webhook_stack
        self.step_functions_arn = step_functions_arn
        self.user_pool = user_pool
        self.user_pool_client = user_pool_client
        self.cloudfront_domain = cloudfront_domain
        self.audio_debrief_lambda = audio_debrief_lambda
        self.push_api_lambda = push_api_lambda

        # Create Lambda functions for API endpoints
        self._create_lambda_functions()

        # Create API Gateway
        self._create_api_gateway()

    def _create_lambda_functions(self) -> None:
        """Create Lambda functions for API endpoints"""
        
        # IAM Note: API Lambdas share webhook_lambda_role for simplicity (single-user app).
        # For multi-user production, split into per-Lambda roles with least-privilege.

        # Configuration API Lambda
        self.config_lambda = lambda_.Function(
            self, "ConfigurationAPI",
            function_name="StravaAIBoost-ConfigurationAPI",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="api.configuration_api.handler",
            code=lambda_.Code.from_asset(
                "lambda_functions",
                # Bytecode caches are regenerated by any local test run and would
                # otherwise change the asset hash, forcing pointless redeploys of
                # every function and making `cdk diff` useless as a
                # deployed-equals-source signal.
                exclude=["**/__pycache__", "**/*.pyc"],
            ),
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(30),
            memory_size=256,
            role=self.core_stack.webhook_lambda_role,
            environment={
                "ACTIVITIES_TABLE": self.core_stack.table_names["activities"],
                "USER_CONFIG_TABLE": self.core_stack.table_names["user_config"],
                "STRAVA_OAUTH_SECRET": self.core_stack.strava_oauth_secret.secret_name,
                "CAMPUS_COACH_SECRET": self.core_stack.campus_coach_secret.secret_name,
                "INTERVALS_ICU_SECRET": self.core_stack.intervals_icu_secret.secret_name,
                "DEFAULT_USER_ID": os.environ.get("DEFAULT_USER_ID", ""),
                "COGNITO_USER_POOL_ID": self.user_pool.user_pool_id if self.user_pool else ""
            }
        )

        # Grant Secrets Manager permissions to config lambda
        self.core_stack.strava_oauth_secret.grant_read(self.config_lambda)
        self.core_stack.campus_coach_secret.grant_read(self.config_lambda)
        self.core_stack.intervals_icu_secret.grant_read(self.config_lambda)
        self.core_stack.intervals_icu_secret.grant_write(self.config_lambda)
        
        # Allow config Lambda to set custom:strava_id on Cognito users
        if self.user_pool:
            self.config_lambda.add_to_role_policy(
                iam.PolicyStatement(
                    effect=iam.Effect.ALLOW,
                    actions=["cognito-idp:AdminUpdateUserAttributes"],
                    resources=[self.user_pool.user_pool_arn]
                )
            )

        # Dashboard API Lambda
        self.dashboard_lambda = lambda_.Function(
            self, "DashboardAPI",
            function_name="StravaAIBoost-DashboardAPI",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="api.dashboard_api.handler",
            code=lambda_.Code.from_asset(
                "lambda_functions",
                # Bytecode caches are regenerated by any local test run and would
                # otherwise change the asset hash, forcing pointless redeploys of
                # every function and making `cdk diff` useless as a
                # deployed-equals-source signal.
                exclude=["**/__pycache__", "**/*.pyc"],
            ),
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(30),
            memory_size=256,
            role=self.core_stack.webhook_lambda_role,
            environment={
                "ACTIVITIES_TABLE": self.core_stack.table_names["activities"],
                "USER_CONFIG_TABLE": self.core_stack.table_names["user_config"],
                "COACHING_SESSIONS_TABLE": self.core_stack.table_names["coaching_sessions"],
                "WELLNESS_TABLE": self.core_stack.table_names["wellness"],
                "STRAVA_OAUTH_SECRET": self.core_stack.strava_oauth_secret.secret_name,
                "DEFAULT_USER_ID": self.node.try_get_context("default_user_id") or "",
                # Sole owner of the Campus plan (the table has no user key): GET
                # /plan/workouts answers 403 to any other claim, or to all when empty.
                "CAMPUS_OWNER_STRAVA_ID": str(self.node.try_get_context("default_user_id") or ""),
                "RECAP_TABLE": "strava-ai-boost-weekly-recaps",
                "AUDIO_DEBRIEF_BUCKET": f"strava-ai-boost-audio-debriefs-{Aws.ACCOUNT_ID}",
                # Watch RANGE alerts for Campus `range` steps (docs/design/campus-paces.md C).
                # Off unless the context flag is exactly "true". Only this Lambda maps
                # sessions to .workout files (api/plan_workouts.py).
                "RANGE_ALERTS_ENABLED": (
                    "true"
                    if str(self.node.try_get_context("range_alerts_enabled")).lower() == "true"
                    else "false"
                ),
            }
        )
        
        # Grant Secrets Manager permissions to dashboard lambda
        self.core_stack.strava_oauth_secret.grant_read(self.dashboard_lambda)

        # Grant DashboardAPI permission to invoke WeeklyAudioRecap Lambda (on-demand recap generation)
        self.dashboard_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["lambda:InvokeFunction"],
                resources=[f"arn:aws:lambda:{Aws.REGION}:{Aws.ACCOUNT_ID}:function:StravaAIBoost-WeeklyAudioRecap"],
            )
        )
        # Grant DashboardAPI read access to recaps table and S3 for presigned URLs
        self.dashboard_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:Query", "dynamodb:GetItem"],
                resources=[f"arn:aws:dynamodb:{Aws.REGION}:{Aws.ACCOUNT_ID}:table/strava-ai-boost-weekly-recaps"],
            )
        )
        self.dashboard_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["s3:GetObject"],
                resources=[f"arn:aws:s3:::strava-ai-boost-audio-debriefs-{Aws.ACCOUNT_ID}/recaps/*"],
            )
        )

        # A4: DashboardAPI reads the wellness table for GET /home/summary. The
        # dashboard uses the SHARED webhook_lambda_role (single-user project);
        # this is accepted and intentional. Read-only here: GetItem + Query, no
        # writes (WellnessSync/CampusCoachSync own the writes).
        owner = str(self.node.try_get_context("default_user_id") or "")
        self.dashboard_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:GetItem", "dynamodb:Query"],
                resources=[self.core_stack.table_arns["wellness"]],
                conditions={"ForAllValues:StringEquals": {"dynamodb:LeadingKeys": [owner]}},
            )
        )

        # User Preferences API Lambda
        self.preferences_lambda = lambda_.Function(
            self, "UserPreferencesAPI",
            function_name="StravaAIBoost-UserPreferencesAPI",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="api.user_preferences_api.handler",
            code=lambda_.Code.from_asset(
                "lambda_functions",
                # Bytecode caches are regenerated by any local test run and would
                # otherwise change the asset hash, forcing pointless redeploys of
                # every function and making `cdk diff` useless as a
                # deployed-equals-source signal.
                exclude=["**/__pycache__", "**/*.pyc"],
            ),
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(10),
            memory_size=128,
            role=self.core_stack.webhook_lambda_role,
            environment={
                "USER_CONFIG_TABLE": self.core_stack.table_names["user_config"],
                "DEFAULT_USER_ID": os.environ.get("DEFAULT_USER_ID", "")
            }
        )

        feedback_code = lambda_.Code.from_asset(
            "lambda_functions",
            exclude=["**/__pycache__", "**/*.pyc"],
        )
        feedback_environment = {
            "ACTIVITIES_TABLE": self.core_stack.table_names["activities"],
        }

        # Dedicated roles keep this authenticated API slice limited to the exact
        # table operations each handler uses. Neither Lambda can scan or query.
        self.input_status_lambda = lambda_.Function(
            self, "InputStatus",
            function_name="StravaAIBoost-InputStatus",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="athlete_input.input_status.handler",
            code=feedback_code,
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(10),
            memory_size=128,
            environment=feedback_environment,
        )
        self.input_status_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:GetItem"],
                resources=[self.core_stack.table_arns["activities"]],
            )
        )

        self.input_submit_lambda = lambda_.Function(
            self, "InputSubmit",
            function_name="StravaAIBoost-InputSubmit",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="athlete_input.input_submit.handler",
            code=feedback_code,
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(10),
            memory_size=128,
            environment=feedback_environment,
        )
        self.input_submit_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["dynamodb:GetItem", "dynamodb:UpdateItem"],
                resources=[self.core_stack.table_arns["activities"]],
            )
        )
        # SendTaskSuccess has no resource type in IAM, so AWS requires Resource "*".
        # Keep it in its own statement so no other action inherits that scope.
        self.input_submit_lambda.add_to_role_policy(
            iam.PolicyStatement(
                actions=["states:SendTaskSuccess"],
                resources=["*"],
            )
        )
        
        # AgentCore Health Check Lambda
        agentcore_env = {
        }
        
        # Load AgentCore agent ARNs from .env.agentcore if available
        from .env_loader import load_agentcore_agent_arns
        agentcore_env.update(load_agentcore_agent_arns())
        
        self.agentcore_health_lambda = lambda_.Function(
            self, "AgentCoreHealthCheck",
            function_name="StravaAIBoost-AgentCoreHealthCheck",
            runtime=lambda_.Runtime.PYTHON_3_12,
            handler="api.agentcore_health_check.handler",
            code=lambda_.Code.from_asset(
                "lambda_functions",
                # Bytecode caches are regenerated by any local test run and would
                # otherwise change the asset hash, forcing pointless redeploys of
                # every function and making `cdk diff` useless as a
                # deployed-equals-source signal.
                exclude=["**/__pycache__", "**/*.pyc"],
            ),
            layers=[self.core_stack.dependencies_layer],
            timeout=Duration.seconds(10),
            memory_size=128,
            role=self.core_stack.webhook_lambda_role,
            environment=agentcore_env
        )
        
        # Grant AgentCore permissions - scoped to agent runtime ARNs
        agentcore_resources = []
        for arn_key in ['CONTENT_GENERATION_AGENT_ARN']:
            if arn_key in agentcore_env:
                agentcore_resources.append(agentcore_env[arn_key])
        if not agentcore_resources:
            agentcore_resources = [
                f"arn:aws:bedrock-agentcore:{self.region}:{self.account}:runtime/*"
            ]
        self.agentcore_health_lambda.add_to_role_policy(
            iam.PolicyStatement(
                effect=iam.Effect.ALLOW,
                actions=[
                    "bedrock-agentcore:InvokeAgentRuntime",
                    "bedrock-agentcore:GetAgentRuntime"
                ],
                resources=agentcore_resources
            )
        )

    def _create_api_gateway(self) -> None:
        """Create API Gateway with Cognito authentication"""
        
        # Build allowed origins
        allowed_origins = [
            "http://localhost:3000", "http://127.0.0.1:3000",
            "http://localhost:5173", "http://127.0.0.1:5173",
        ]
        if self.cloudfront_domain:
            allowed_origins.append(f"https://{self.cloudfront_domain}")

        # Create REST API
        self.api = apigateway.RestApi(
            self, "StravaAIBoostAPI",
            rest_api_name="Strava AI Boost Local Interface API",
            description="REST API for Strava AI Boost (Cognito auth)",
            default_cors_preflight_options=apigateway.CorsOptions(
                allow_origins=allowed_origins,
                allow_methods=["GET", "POST", "PUT", "DELETE", "OPTIONS"],
                allow_headers=["Content-Type", "Authorization", "X-Requested-With"]
            ),
            endpoint_configuration=apigateway.EndpointConfiguration(
                types=[apigateway.EndpointType.REGIONAL]
            ),
            deploy_options=apigateway.StageOptions(
                throttling_rate_limit=100,
                throttling_burst_limit=200,
                method_options={
                    "/activities/{activityId}/feedback/POST": apigateway.MethodDeploymentOptions(
                        throttling_rate_limit=FEEDBACK_POST_THROTTLE_RATE_LIMIT,
                        throttling_burst_limit=FEEDBACK_POST_THROTTLE_BURST_LIMIT,
                    ),
                },
                **api_stage_logging_options(self, "ApiAccessLogs"),
            )
        )

        # Cognito Authorizer (primary auth for frontend)
        self.cognito_authorizer = None
        if self.user_pool:
            self.cognito_authorizer = apigateway.CognitoUserPoolsAuthorizer(
                self, "CognitoAuthorizer",
                cognito_user_pools=[self.user_pool],
                authorizer_name="StravaAIBoost-CognitoAuth",
            )
        
        # Create API resources and methods (Cognito-authorized)

        # /config resource for configuration management
        config_resource = self.api.root.add_resource("config")
        
        # Strava app config endpoint (check if configured)
        strava_resource = config_resource.add_resource("strava")
        strava_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
            method_responses=[
                apigateway.MethodResponse(status_code="200"),
                apigateway.MethodResponse(status_code="500")
            ]
        )
        
        # OAuth endpoints
        oauth_resource = config_resource.add_resource("oauth")
        oauth_resource.add_method(
            "GET", 
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
            method_responses=[
                apigateway.MethodResponse(status_code="200"),
                apigateway.MethodResponse(status_code="400"),
                apigateway.MethodResponse(status_code="401"),
                apigateway.MethodResponse(status_code="403"),
                apigateway.MethodResponse(status_code="500")
            ]
        )
        oauth_resource.add_method(
            "POST",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        oauth_resource.add_method(
            "DELETE",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # Module management endpoints
        modules_resource = config_resource.add_resource("modules")
        modules_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        modules_resource.add_method(
            "POST",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        
        module_resource = modules_resource.add_resource("{module_id}")
        module_resource.add_method(
            "PUT",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        module_resource.add_method(
            "DELETE",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # Enhancement control endpoints
        enhancement_resource = config_resource.add_resource("enhancement")
        enhancement_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        enhancement_resource.add_method(
            "POST",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /dashboard resource for statistics and monitoring
        dashboard_resource = self.api.root.add_resource("dashboard")
        
        # Statistics endpoint
        stats_resource = dashboard_resource.add_resource("stats")
        stats_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # Activity history endpoint
        activities_resource = dashboard_resource.add_resource("activities")
        activities_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        
        # System stats endpoint (total activities, success rate, queue depth)
        system_resource = dashboard_resource.add_resource("system")
        system_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /coach resource for coaching summary
        coach_resource = self.api.root.add_resource("coach")
        coach_summary_resource = coach_resource.add_resource("summary")
        coach_summary_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /coach/recaps endpoint (GET list + POST generate)
        coach_recaps_resource = coach_resource.add_resource("recaps")
        coach_recaps_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        coach_recaps_resource.add_method(
            "POST",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /plan/workouts: remaining Campus sessions as Apple .workout files.
        # Cognito here; the handler then requires custom:strava_id == CAMPUS_OWNER_STRAVA_ID.
        plan_resource = self.api.root.add_resource("plan")
        plan_workouts_resource = plan_resource.add_resource("workouts")
        plan_workouts_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /home/summary: owner-only home dashboard (Cognito here; the handler then
        # requires custom:strava_id == CAMPUS_OWNER_STRAVA_ID, same as /plan/workouts).
        home_resource = self.api.root.add_resource("home")
        home_summary_resource = home_resource.add_resource("summary")
        home_summary_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.dashboard_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )

        # /preferences resource for user preferences
        preferences_resource = self.api.root.add_resource("preferences")
        preferences_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.preferences_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        preferences_resource.add_method(
            "POST",
            apigateway.LambdaIntegration(self.preferences_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        
        # /health resource for AgentCore health check
        health_resource = self.api.root.add_resource("health")
        agentcore_health_resource = health_resource.add_resource("agentcore")
        agentcore_health_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.agentcore_health_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        
        # Shared /activities/{activityId} parent for feedback and optional audio.
        # It is created once so enabling audio cannot produce a duplicate variable
        # resource such as /activities/{id} beside /activities/{activityId}.
        activities_root = self.api.root.add_resource("activities")
        activity_item = activities_root.add_resource("{activityId}")

        # Feedback is personal health/training data. If this stack is instantiated
        # without Cognito (some isolated tests do that), fail closed by omitting the
        # methods rather than silently exposing them with AuthorizationType.NONE.
        if self.cognito_authorizer is not None:
            feedback_resource = activity_item.add_resource("feedback")
            feedback_resource.add_method(
                "GET",
                apigateway.LambdaIntegration(self.input_status_lambda),
                authorizer=self.cognito_authorizer,
                authorization_type=apigateway.AuthorizationType.COGNITO,
                method_responses=[
                    apigateway.MethodResponse(status_code="200"),
                    apigateway.MethodResponse(status_code="400"),
                    apigateway.MethodResponse(status_code="403"),
                    apigateway.MethodResponse(status_code="500"),
                ],
            )
            feedback_resource.add_method(
                "POST",
                apigateway.LambdaIntegration(self.input_submit_lambda),
                authorizer=self.cognito_authorizer,
                authorization_type=apigateway.AuthorizationType.COGNITO,
                method_responses=[
                    apigateway.MethodResponse(status_code="202"),
                    apigateway.MethodResponse(status_code="400"),
                    apigateway.MethodResponse(status_code="403"),
                    apigateway.MethodResponse(status_code="409"),
                    apigateway.MethodResponse(status_code="500"),
                ],
            )

        # /activities/{activityId}/audio-url — presigned URL for voice debrief MP3
        if self.audio_debrief_lambda is not None:
            audio_url_resource = activity_item.add_resource("audio-url")
            audio_url_resource.add_method(
                "GET",
                apigateway.LambdaIntegration(self.audio_debrief_lambda),
                authorizer=self.cognito_authorizer,
                authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
                method_responses=[
                    apigateway.MethodResponse(status_code="200"),
                    apigateway.MethodResponse(status_code="400"),
                    apigateway.MethodResponse(status_code="403"),
                    apigateway.MethodResponse(status_code="404"),
                    apigateway.MethodResponse(status_code="500"),
                ],
            )

        # /push resource for opt-in Web Push subscription
        if self.push_api_lambda is not None:
            push_resource = self.api.root.add_resource("push")
            # Every push route, the VAPID application server key included, sits
            # behind Cognito like the rest of this API (no unauthenticated
            # endpoint). PushApi still returns 401 by itself when the identity claim
            # is missing.
            app_server_key_resource = push_resource.add_resource("application-server-key")
            app_server_key_resource.add_method(
                "GET",
                apigateway.LambdaIntegration(self.push_api_lambda),
                authorizer=self.cognito_authorizer,
                authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
                method_responses=[
                    apigateway.MethodResponse(status_code="200"),
                    apigateway.MethodResponse(status_code="401"),
                    apigateway.MethodResponse(status_code="500"),
                ],
            )
            push_subscribe_resource = push_resource.add_resource("subscribe")
            for push_method in ("POST", "DELETE"):
                push_subscribe_resource.add_method(
                    push_method,
                    apigateway.LambdaIntegration(self.push_api_lambda),
                    authorizer=self.cognito_authorizer,
                    authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
                    method_responses=[
                        apigateway.MethodResponse(status_code="200"),
                        apigateway.MethodResponse(status_code="400"),
                        apigateway.MethodResponse(status_code="401"),
                        apigateway.MethodResponse(status_code="500"),
                    ],
                )

        # /test resource for connection testing
        test_resource = self.api.root.add_resource("test")
        strava_connection_resource = test_resource.add_resource("strava-connection")
        strava_connection_resource.add_method(
            "GET",
            apigateway.LambdaIntegration(self.config_lambda),
            authorizer=self.cognito_authorizer,
            authorization_type=apigateway.AuthorizationType.COGNITO if self.cognito_authorizer else apigateway.AuthorizationType.NONE,
        )
        
        # Add request validation
        self.api.add_request_validator(
            "RequestValidator",
            validate_request_body=True,
            validate_request_parameters=True
        )

        self._create_operational_alarms()

    def _create_operational_alarms(self) -> None:
        """Alarm on feedback Lambda failures and API 5XX/4XX rate-limit signals."""
        topic = sns.Topic.from_topic_arn(
            self,
            "OpsAlertsTopic",
            f"arn:{Aws.PARTITION}:sns:{Aws.REGION}:{Aws.ACCOUNT_ID}:{OPS_ALERTS_TOPIC_NAME}",
        )
        alarm_action = cw_actions.SnsAction(topic)
        period = Duration.minutes(5)

        for alarm_id, alarm_name, function in (
            (
                "InputStatusErrorsAlarm",
                "strava-ai-boost-input-status-errors",
                self.input_status_lambda,
            ),
            (
                "InputSubmitErrorsAlarm",
                "strava-ai-boost-input-submit-errors",
                self.input_submit_lambda,
            ),
        ):
            alarm = cloudwatch.Alarm(
                self,
                alarm_id,
                alarm_name=alarm_name,
                alarm_description=f"{function.function_name} reported a Lambda error",
                metric=function.metric_errors(period=period),
                threshold=1,
                evaluation_periods=1,
                comparison_operator=(
                    cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD
                ),
                treat_missing_data=cloudwatch.TreatMissingData.NOT_BREACHING,
            )
            alarm.add_alarm_action(alarm_action)

        api_5xx = cloudwatch.Alarm(
            self,
            "ApiServerErrorsAlarm",
            alarm_name="strava-ai-boost-api-5xx-errors",
            alarm_description="The authenticated frontend API returned a 5XX response",
            metric=self.api.metric_server_error(period=period, statistic="Sum"),
            threshold=1,
            evaluation_periods=1,
            comparison_operator=cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD,
            treat_missing_data=cloudwatch.TreatMissingData.NOT_BREACHING,
        )
        api_5xx.add_alarm_action(alarm_action)

        # API Gateway reports method throttles (429) in 4XXError rather than a
        # dedicated throttle series. A threshold avoids paging on one expired JWT
        # while still making sustained throttling or auth failures visible.
        api_4xx = cloudwatch.Alarm(
            self,
            "ApiThrottlesAndClientErrorsAlarm",
            alarm_name="strava-ai-boost-api-throttles-or-client-errors",
            alarm_description=(
                "The authenticated frontend API returned at least 10 4XX responses "
                "in five minutes, including any throttled requests"
            ),
            metric=self.api.metric_client_error(period=period, statistic="Sum"),
            threshold=10,
            evaluation_periods=1,
            comparison_operator=cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD,
            treat_missing_data=cloudwatch.TreatMissingData.NOT_BREACHING,
        )
        api_4xx.add_alarm_action(alarm_action)

    @property
    def api_url(self) -> str:
        """Return the API Gateway URL"""
        return self.api.url