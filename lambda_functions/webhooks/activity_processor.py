"""
Activity Processor Lambda Function

Processes activities from SQS queue and triggers Step Functions workflow.
Handles error recovery.

Reliability plan, lot 3:
- the Step Functions execution name is deterministic (``activity-{id}-v{version}``,
  version = the webhook event_time), so a redelivered SQS message cannot start a
  second pipeline: Step Functions refuses the duplicate name and we treat that
  refusal (ExecutionAlreadyExists) as "already started".
- a late athlete dictation (``update`` webhook after the activity was completed)
  is no longer dropped: see ``decide_late_dictation``.
"""

import difflib
import json
import os
import re
from datetime import datetime, timedelta, UTC
from typing import Any, Dict, List, Optional

import boto3
import requests
from botocore.exceptions import ClientError
from shared.logger import get_logger, metrics, MetricUnit

logger = get_logger("activity_processor")

# Initialize AWS clients
stepfunctions = boto3.client('stepfunctions')
dynamodb = boto3.resource('dynamodb')
sqs = boto3.client('sqs')
secretsmanager = boto3.client('secretsmanager')

# Environment variables
ACTIVITIES_TABLE = os.environ['ACTIVITIES_TABLE']
STRAVA_OAUTH_SECRET = os.environ['STRAVA_OAUTH_SECRET']
STEP_FUNCTIONS_ARN = os.environ['STEP_FUNCTIONS_ARN']

# Get SQS queue URL from environment or construct it
PROCESSING_QUEUE_URL = os.environ.get('PROCESSING_QUEUE_URL', 
    f"https://sqs.{os.environ.get('AWS_REGION', 'eu-west-1')}.amazonaws.com/{os.environ.get('AWS_ACCOUNT_ID', '')}/strava-ai-boost-activity-processing")

STRAVA_API_BASE = "https://www.strava.com/api/v3"

# Step Functions execution names: 1-80 chars, letters, digits, '-' and '_' only.
EXECUTION_NAME_MAX_LEN = 80
_EXECUTION_NAME_FORBIDDEN = re.compile(r'[^A-Za-z0-9_-]')

# Late dictation (BACKLOG P1 "Dictée tardive perdue").
GENERATED_SIGNATURE = '@Generated by Strava AI Boost'
# Same markers as activity_fetcher._GENERATED_MARKERS: any paragraph carrying one
# is our own output, never athlete text.
_GENERATED_MARKERS = (GENERATED_SIGNATURE, 'Strava AI Boost Coach')
# A changed paragraph this close to one of ours is a hand edit, not a dictation.
MANUAL_EDIT_SIMILARITY = 0.6
# Hard loop guard on top of the diff: at most this many merges per activity.
MAX_LATE_MERGES = 3

# Decision values returned by decide_late_dictation
REPROCESS = 'reprocess'
SKIP = 'skip'


# @log_metrics is what flushes add_metric to CloudWatch (EMF on stdout).
# Without it the metrics are buffered and silently dropped.
@metrics.log_metrics
def handler(event: Dict[str, Any], context: Any) -> Dict[str, Any]:
    """
    Lambda handler for SQS-triggered activity processing
    
    Receives activity notifications from SQS and starts Step Functions workflow.
    Uses batch item failures to prevent deleting messages when Step Functions fails.
    """
    batch_item_failures = []
    
    try:
        # Process SQS records
        for record in event.get('Records', []):
            try:
                process_activity_record(record)
            except Exception as e:
                # Add failed record to batch item failures
                # This prevents SQS from deleting the message, allowing retry
                logger.error(f"Failed to process record {record.get('messageId')}: {str(e)}")
                batch_item_failures.append({
                    "itemIdentifier": record['messageId']
                })
        
        # Publish business metrics
        processed = len(event.get('Records', [])) - len(batch_item_failures)
        if processed > 0:
            metrics.add_metric(name="ActivitiesProcessed", unit=MetricUnit.Count, value=processed)
        if batch_item_failures:
            metrics.add_metric(name="ActivitiesProcessFailed", unit=MetricUnit.Count, value=len(batch_item_failures))

        # Return batch item failures to SQS
        # Messages with failures will be retried, successful ones will be deleted
        return {
            'batchItemFailures': batch_item_failures
        }
        
    except (ClientError, json.JSONDecodeError, KeyError, ValueError) as e:
        logger.error(f"Activity processor critical error: {str(e)}", exc_info=True)
        # Return all messages as failures to prevent deletion
        return {
            'batchItemFailures': [
                {"itemIdentifier": record['messageId']} 
                for record in event.get('Records', [])
            ]
        }


def process_activity_record(record: Dict[str, Any]) -> None:
    """
    Process a single activity record from SQS
    
    Raises exception on failure to signal batch item failure to SQS
    """
    activity_id = None
    
    try:
        # Parse SQS message
        message_body = json.loads(record['body'])
        activity_id = message_body['activity_id']
        user_id = message_body['user_id']
        
        logger.info(f"Processing activity {activity_id} for user {user_id}")
        
        # Check if activity is already processed or being processed (prevent webhook update loops)
        if should_skip_processing(activity_id, message_body):
            logger.info(f"Skipping activity {activity_id} - already processed or processing")
            return  # Exit successfully so SQS deletes the message

        late_dictation = message_body.get('late_dictation')
        if late_dictation:
            # The activity already had its Enduraw wait on first processing.
            message_body['enduraw_waited'] = True
            if not apply_late_dictation_merge(activity_id, late_dictation):
                logger.info(f"Late dictation merge for {activity_id} lost a race, skipping")
                return
        
        # Fetch user configuration to check module settings
        user_config = fetch_user_configuration(user_id)
        
        # Check if Enduraw module is enabled and we haven't waited yet
        enduraw_config = user_config.get('modules_config', {}).get('enduraw', {})
        enduraw_enabled = enduraw_config.get('enabled', False)
        enduraw_waited = message_body.get('enduraw_waited', False)
        
        # Debug logs
        logger.info(f"Enduraw check - config: {enduraw_config}, enabled: {enduraw_enabled}, waited: {enduraw_waited}")
        
        if enduraw_enabled and not enduraw_waited:
            logger.info(f"Enduraw module enabled for activity {activity_id}, delaying by 2 minutes for Enduraw processing")
            
            # Update activity status to indicate Enduraw wait
            update_activity_status(activity_id, 'waiting_enduraw', 'Waiting 2 minutes for Enduraw Report processing', critical=False)
            
            # Mark that we've initiated Enduraw wait
            message_body['enduraw_waited'] = True
            message_body['enduraw_delay_started_at'] = datetime.now(UTC).isoformat()
            
            # Send back to SQS with 2-minute delay
            sqs.send_message(
                QueueUrl=PROCESSING_QUEUE_URL,
                MessageBody=json.dumps(message_body),
                DelaySeconds=120  # 2 minutes for Enduraw processing
            )
            
            logger.info(f"Activity {activity_id} requeued with 2-minute delay for Enduraw processing")
            # Exit successfully so original message is deleted
            return
        
        # Log if Enduraw wait was completed
        if enduraw_enabled and enduraw_waited:
            enduraw_delay_started = message_body.get('enduraw_delay_started_at', 'unknown')
            logger.info(f"Enduraw wait completed for activity {activity_id} (started at {enduraw_delay_started})")
        
        # Update activity status to processing
        update_activity_status(activity_id, 'processing', critical=True)
        
        # Start Step Functions workflow with Enduraw metadata
        execution_arn = start_step_functions_workflow(activity_id, user_id, message_body, enduraw_enabled and enduraw_waited)
        
        if execution_arn:
            logger.info(f"Started Step Functions workflow for activity {activity_id}: {execution_arn}")
            # Step Functions retries the transient task errors itself (lot 3); its
            # terminal failures are handled by the Step Functions error handler.
        else:
            logger.error(f"Failed to start Step Functions workflow for activity {activity_id}")
            update_activity_status(activity_id, 'failed', 'Failed to start workflow', critical=False)
            # Raise exception to trigger SQS retry via batch item failure
            raise Exception("Failed to start Step Functions workflow")
        
    except Exception as e:
        logger.error(f"Failed to process activity record: {str(e)}")
        # Update status to failed if we have activity_id
        if activity_id:
            update_activity_status(activity_id, 'failed', str(e), critical=False)
        # Re-raise to trigger batch item failure (message will be retried)
        raise




def should_skip_processing(activity_id: str, message_body: Dict[str, Any]) -> bool:
    """
    Check if activity should be skipped to prevent webhook update loops
    
    Returns True if:
    - Activity is already completed, EXCEPT an `update` carrying a late athlete
      dictation (see decide_late_dictation): then the decision is stored in
      message_body['late_dictation'] and False is returned
    - Activity is currently processing 
    - Activity failed recently (within 1 hour) to avoid rapid retries
    - Webhook is an 'update' event and activity was already processed
    """
    try:
        table = dynamodb.Table(ACTIVITIES_TABLE)
        
        # Check if activity exists in DynamoDB
        response = table.get_item(Key={'activity_id': activity_id})
        
        if 'Item' not in response:
            # New activity, should process
            logger.info(f"New activity {activity_id}, proceeding with processing")
            return False
        
        activity = response['Item']
        processing_status = activity.get('processing_status', 'unknown')
        webhook_data = message_body.get('webhook_data', {})
        aspect_type = webhook_data.get('aspect_type', 'unknown')
        
        # Completed: only a late athlete dictation reopens it
        if processing_status == 'completed':
            if aspect_type == 'update':
                return not check_late_dictation(activity_id, activity, message_body)
            logger.info(f"Activity {activity_id} already completed, skipping")
            return True
        
        # Skip if currently processing (avoid concurrent processing)
        if processing_status == 'processing':
            logger.info(f"Activity {activity_id} currently processing, skipping")
            return True
        
        # Skip if waiting for Enduraw (avoid concurrent processing during wait)
        # BUT allow processing if enduraw_waited flag is set (message after 2-min delay)
        if processing_status == 'waiting_enduraw':
            enduraw_waited = message_body.get('enduraw_waited', False)
            if not enduraw_waited:
                logger.info(f"Activity {activity_id} waiting for Enduraw, skipping")
                return True
            else:
                logger.info(f"Activity {activity_id} Enduraw wait completed, proceeding with processing")
                # Force processing - return False immediately to bypass other checks
                return False
        
        # For update webhooks, be more restrictive
        if aspect_type == 'update':
            # Skip if failed recently (within 1 hour) to avoid rapid retries from updates
            updated_at = activity.get('updated_at')
            if processing_status == 'failed' and updated_at:
                try:
                    last_update = datetime.fromisoformat(updated_at.replace('Z', '+00:00'))
                    if last_update.tzinfo is None:
                        last_update = last_update.replace(tzinfo=UTC)
                    if datetime.now(UTC) - last_update < timedelta(hours=1):
                        logger.info(f"Activity {activity_id} failed recently, skipping update webhook")
                        return True
                except (ValueError, AttributeError) as e:
                    logger.warning(f"Error parsing updated_at timestamp: {e}")
        
        # For create webhooks or failed activities (older than 1 hour), allow processing
        logger.info(f"Activity {activity_id} status: {processing_status}, aspect: {aspect_type}, proceeding")
        return False
        
    except (ClientError, ValueError, TypeError) as e:
        logger.error(f"Error checking processing status for activity {activity_id}: {str(e)}")
        # On error, allow processing to avoid blocking legitimate requests
        return False


# --- Late dictation (BACKLOG P1) ---

def _normalize(text: Optional[str]) -> str:
    """Whitespace-insensitive form used for every comparison."""
    return re.sub(r'\s+', ' ', (text or '')).strip()


def _paragraphs(text: Optional[str]) -> List[str]:
    """Blank-line separated paragraphs, normalized, empty ones dropped."""
    return [p for p in (_normalize(chunk) for chunk in re.split(r'\n\s*\n', text or '')) if p]


def _is_generated(paragraph: str) -> bool:
    return any(marker in paragraph for marker in _GENERATED_MARKERS)


def decide_late_dictation(activity: Dict[str, Any], current_description: Optional[str]) -> Dict[str, Any]:
    """Decide whether an `update` of a COMPLETED activity carries a late dictation.

    Pure function (no I/O) so the four cases are unit-testable:

    - our own write (current Strava description == the enhanced_description we
      pushed) -> skip. This is the natural loop guard: the update webhook fired by
      UpdateStrava always lands here.
    - the athlete edited our text by hand (final_description recorded by the
      nightly analyzer differs from ours, our signature is gone, one of our
      paragraphs is missing, or a new paragraph is a near copy of one of ours)
      -> skip: a reprocess would overwrite his edit.
    - nothing new (every paragraph is ours or already in original_description)
      -> skip.
    - otherwise the new paragraphs are athlete text -> reprocess, with
      original_description extended by that text so the generation sees it.

    Returns {'action': 'reprocess'|'skip', 'reason': str, 'new_text': str,
    'merged_original': str}.
    """
    def skip(reason: str) -> Dict[str, Any]:
        return {'action': SKIP, 'reason': reason, 'new_text': '', 'merged_original': ''}

    merges_done = int(activity.get('late_merge_count') or 0)
    if merges_done >= MAX_LATE_MERGES:
        return skip('merge_cap_reached')

    current = current_description or ''
    generated = activity.get('enhanced_description') or ''
    original = activity.get('original_description') or ''
    final = activity.get('final_description')

    if not _normalize(current):
        return skip('empty_description')
    if not _normalize(generated):
        return skip('no_generated_text')
    if _normalize(current) == _normalize(generated):
        return skip('own_write')
    if final is not None and _normalize(final) != _normalize(generated):
        return skip('manual_edit_recorded')
    if GENERATED_SIGNATURE not in current:
        # Our text (and its signature) was replaced: regenerating would
        # overwrite what the athlete wrote instead of it.
        return skip('generated_text_replaced')

    current_paragraphs = _paragraphs(current)
    generated_paragraphs = [p for p in _paragraphs(generated) if not _is_generated(p)]
    current_set = set(current_paragraphs)
    if any(p not in current_set for p in generated_paragraphs):
        return skip('manual_edit')

    generated_set = set(_paragraphs(generated))
    original_norm = _normalize(original)
    new_paragraphs = [
        p for p in current_paragraphs
        if p not in generated_set and not _is_generated(p) and p not in original_norm
    ]
    if not new_paragraphs:
        return skip('nothing_new')

    for paragraph in new_paragraphs:
        for ours in generated_paragraphs:
            if difflib.SequenceMatcher(None, paragraph, ours).ratio() >= MANUAL_EDIT_SIMILARITY:
                return skip('manual_edit')

    new_text = '\n\n'.join(new_paragraphs)
    merged_original = f"{original.rstrip()}\n\n{new_text}" if original.strip() else new_text
    return {
        'action': REPROCESS,
        'reason': 'late_dictation',
        'new_text': new_text,
        'merged_original': merged_original,
    }


def check_late_dictation(activity_id: str, activity: Dict[str, Any], message_body: Dict[str, Any]) -> bool:
    """Fetch the current Strava description and run decide_late_dictation.

    True means "reprocess": the decision is stored in message_body['late_dictation']
    for process_activity_record. Never raises: any failure is a skip, because an
    error here must not flip a completed activity to 'failed'.
    """
    try:
        current_description = fetch_strava_description(activity_id)
    except (requests.RequestException, ValueError, KeyError, ClientError) as e:
        logger.warning(f"Late dictation check for {activity_id} could not read Strava, skipping: {e}")
        metrics.add_metric(name="LateDictationCheckFailed", unit=MetricUnit.Count, value=1)
        return False

    decision = decide_late_dictation(activity, current_description)
    logger.info(
        f"Late dictation decision for completed activity {activity_id}: "
        f"{decision['action']} ({decision['reason']})"
    )
    if decision['action'] != REPROCESS:
        return False

    metrics.add_metric(name="LateDictationReprocess", unit=MetricUnit.Count, value=1)
    message_body['late_dictation'] = {
        'new_text': decision['new_text'],
        'merged_original': decision['merged_original'],
        'previous_merge_count': int(activity.get('late_merge_count') or 0),
    }
    return True


def apply_late_dictation_merge(activity_id: str, late_dictation: Dict[str, Any]) -> bool:
    """Store the merged original text before the reprocess starts.

    The fetcher keeps the stored original_description when Strava's current text
    carries our signature, so writing the merge here is what puts the dictation in
    the generation context. Conditional on the activity still being 'completed' so
    two concurrent update webhooks cannot both reopen it. Returns False on a lost
    race (the other message is already reprocessing) or a write error.
    """
    table = dynamodb.Table(ACTIVITIES_TABLE)
    try:
        table.update_item(
            Key={'activity_id': activity_id},
            UpdateExpression=(
                "SET original_description = :merged, late_dictation_text = :text, "
                "late_dictation_at = :now, late_merge_count = :count"
            ),
            ConditionExpression="processing_status = :completed",
            ExpressionAttributeValues={
                ':merged': late_dictation['merged_original'],
                ':text': late_dictation['new_text'],
                ':now': datetime.now(UTC).isoformat(),
                ':count': int(late_dictation.get('previous_merge_count', 0)) + 1,
                ':completed': 'completed',
            },
        )
        logger.info(f"Late dictation merged into original_description of {activity_id}")
        return True
    except ClientError as e:
        if e.response.get('Error', {}).get('Code') != 'ConditionalCheckFailedException':
            # Never let a failed merge flip a completed activity to 'failed'.
            logger.error(f"Late dictation merge failed for {activity_id}: {e}")
        return False


def get_strava_access_token() -> str:
    """Read the stored Strava access token (read-only).

    The processor role can read the OAuth secret but not refresh/write it, so an
    expired token is reported as an error (the check then skips) instead of being
    refreshed here. A late dictation arrives within the 6h lifetime of the token
    the pipeline itself just refreshed.
    """
    response = secretsmanager.get_secret_value(SecretId=STRAVA_OAUTH_SECRET)
    tokens = json.loads(response['SecretString'])
    access_token = tokens.get('access_token')
    if not access_token:
        raise ValueError("No Strava access token stored")
    expires_at = tokens.get('expires_at')
    if isinstance(expires_at, (int, float)) and expires_at <= datetime.now(UTC).timestamp():
        raise ValueError("Stored Strava access token expired")
    return access_token


def fetch_strava_description(activity_id: str) -> str:
    """Current description of the activity on Strava."""
    access_token = get_strava_access_token()
    response = requests.get(
        f"{STRAVA_API_BASE}/activities/{activity_id}",
        headers={'Authorization': f'Bearer {access_token}'},
        timeout=10,
    )
    response.raise_for_status()
    return response.json().get('description') or ''


def update_activity_status(
    activity_id: str, 
    status: str, 
    error_message: str = None,
    critical: bool = False
) -> None:
    """Update activity processing status in DynamoDB"""
    try:
        table = dynamodb.Table(ACTIVITIES_TABLE)
        
        update_expression = "SET processing_status = :status, updated_at = :timestamp"
        expression_values = {
            ':status': status,
            ':timestamp': datetime.now(UTC).isoformat()  # Use current timestamp
        }
        
        if error_message:
            update_expression += ", error_message = :error"
            expression_values[':error'] = error_message
        
        table.update_item(
            Key={'activity_id': activity_id},
            UpdateExpression=update_expression,
            ExpressionAttributeValues=expression_values
        )
        
        logger.info(f"Updated activity {activity_id} status to {status}")
        
    except ClientError as e:
        logger.error(f"Failed to update activity status: {str(e)}")
        # For critical status updates (like initial processing), raise to trigger retry
        if critical:
            raise
        # For non-critical updates (like final status), don't raise


def build_execution_name(activity_id: str, message_body: Dict[str, Any]) -> str:
    """Deterministic Step Functions execution name `activity-{id}-v{version}`.

    version = the webhook event_time (the create's, or the accepted update's), so a
    redelivered SQS message maps to the same name and Step Functions refuses the
    duplicate. Without an event_time we fall back to "now" (not idempotent, logged).
    Sanitized to Step Functions rules: [A-Za-z0-9_-], at most 80 characters.
    """
    webhook_data = message_body.get('webhook_data') or {}
    version = message_body.get('event_time') or webhook_data.get('event_time')
    if version in (None, ''):
        version = int(datetime.now(UTC).timestamp())
        logger.warning(f"No event_time for activity {activity_id}, execution name is not idempotent")
    if isinstance(version, float) and version.is_integer():
        version = int(version)
    name = _EXECUTION_NAME_FORBIDDEN.sub('-', f"activity-{activity_id}-v{version}")
    return name[:EXECUTION_NAME_MAX_LEN]


def _execution_arn_for(name: str) -> str:
    """ARN of the execution `name` of our state machine."""
    return f"{STEP_FUNCTIONS_ARN.replace(':stateMachine:', ':execution:', 1)}:{name}"


def start_step_functions_workflow(
    activity_id: str, 
    user_id: str, 
    webhook_data: Dict[str, Any],
    enduraw_waited: bool = False
) -> str:
    """Start Step Functions workflow for activity processing.

    ExecutionAlreadyExists is a success: this message (or a duplicate of it)
    already started the pipeline.
    """
    workflow_input = {
        'activity_id': activity_id,
        'user_id': user_id,
        'webhook_data': webhook_data,
        'enduraw_waited': enduraw_waited,
        'processing_started_at': datetime.now(UTC).isoformat()
    }
    execution_name = build_execution_name(activity_id, webhook_data)

    try:
        response = stepfunctions.start_execution(
            stateMachineArn=STEP_FUNCTIONS_ARN,
            name=execution_name,
            input=json.dumps(workflow_input)
        )
    except ClientError as e:
        if e.response.get('Error', {}).get('Code') != 'ExecutionAlreadyExists':
            logger.error(f"Failed to start Step Functions workflow: {str(e)}")
            raise  # SQS retry
        execution_arn = _execution_arn_for(execution_name)
        logger.info(
            f"Execution {execution_name} already exists for activity {activity_id}, "
            "treating as already started"
        )
        metrics.add_metric(name="ExecutionAlreadyExists", unit=MetricUnit.Count, value=1)
        _sync_status_with_existing_execution(activity_id, execution_arn)
        return execution_arn

    execution_arn = response['executionArn']

    # Update activity with execution ARN for tracking
    update_activity_execution_arn(activity_id, execution_arn)

    return execution_arn


def _sync_status_with_existing_execution(activity_id: str, execution_arn: str) -> None:
    """Undo our 'processing' mark when the duplicate's execution already ended."""
    try:
        status = stepfunctions.describe_execution(executionArn=execution_arn).get('status')
    except ClientError as e:
        logger.warning(f"Could not describe existing execution {execution_arn}: {e}")
        return
    if status == 'SUCCEEDED':
        update_activity_status(activity_id, 'completed')
    elif status in ('FAILED', 'TIMED_OUT', 'ABORTED'):
        update_activity_status(activity_id, 'failed', f"Existing execution {status}")


def update_activity_execution_arn(activity_id: str, execution_arn: str) -> None:
    """Update activity record with Step Functions execution ARN"""
    try:
        table = dynamodb.Table(ACTIVITIES_TABLE)
        
        table.update_item(
            Key={'activity_id': activity_id},
            UpdateExpression="SET execution_arn = :arn, processing_status = :status",
            ExpressionAttributeValues={
                ':arn': execution_arn,
                ':status': 'processing'
            }
        )
        
        logger.info(f"Updated activity {activity_id} with execution ARN")
        
    except ClientError as e:
        logger.error(f"Failed to update execution ARN: {str(e)}")

def fetch_user_configuration(user_id: str) -> Dict[str, Any]:
    """
    Fetch user configuration from DynamoDB
    
    Returns user configuration including module settings from user's own record
    """
    try:
        table = dynamodb.Table(os.environ.get('USER_CONFIG_TABLE', 'strava-ai-boost-user-configuration'))
        
        # Fetch user configuration directly
        user_config_response = table.get_item(Key={'user_id': user_id})
        
        if 'Item' in user_config_response:
            user_config = user_config_response['Item']
            logger.info(f"Retrieved configuration for user {user_id}")
            
            # Read modules_config from user's own record
            modules_config_data = user_config.get('modules_config', {})
            
            # Debug: log module structure
            enduraw_config = modules_config_data.get('enduraw', {})
            campus_coach_config = modules_config_data.get('campus_coach', {})
            
            logger.info(f"enduraw config: {enduraw_config}")
            logger.info(f"campus_coach config: {campus_coach_config}")
            
            # Return config in expected format
            return {
                'user_id': user_id,
                'modules_config': {
                    'enduraw': enduraw_config,
                    'campus_coach': campus_coach_config
                },
                'enhancement_enabled': user_config.get('enhancement_enabled', True)
            }
        else:
            # Return default configuration if user doesn't exist
            default_config = {
                'user_id': user_id,
                'modules_config': {
                    'campus_coach': {'enabled': False},
                    'enduraw': {'enabled': False}
                },
                'enhancement_enabled': True
            }
            logger.info(f"No configuration found for user {user_id}, using defaults")
            return default_config
            
    except ClientError as e:
        logger.error(f"Failed to fetch user configuration: {str(e)}")
        # Return minimal default config on error
        return {
            'user_id': user_id,
            'modules_config': {
                'campus_coach': {'enabled': False},
                'enduraw': {'enabled': False}
            },
            'enhancement_enabled': True
        }
