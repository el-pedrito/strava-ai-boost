"""Deterministic post-generation formatting of activity descriptions.

The content agent sometimes returns a wall of text: one 500-character paragraph that
Strava renders as an unreadable block. ``format_paragraphs`` fixes the layout in code,
after generation, without ever changing what is said (reliability lot 4, step 2).

Guarantees:
- only whitespace is ever added, removed or changed: every non-whitespace character of
  the input is present, in order, in the output;
- a body paragraph longer than ``max_chars`` is split at the sentence boundary closest
  to its middle, recursively, until every piece fits or has no boundary left;
- a split never happens inside a number ("5:36/km", "4,5", "4.5"), never mid-sentence,
  and never strands a trailing emoji at the start of the next paragraph;
- paragraphs are separated by exactly one blank line;
- the "📋 Séance Campus Coach" line is never split nor moved, and paragraphs that span
  several lines (lists, the Campus line glued to its text) are left as they are;
- the "📊 Strava AI Boost Coach" block, the "@Generated by Strava AI Boost" signature
  and everything after the first of them are returned verbatim;
- idempotent: ``format_paragraphs(format_paragraphs(x)) == format_paragraphs(x)``.
"""

import re
import unicodedata

DEFAULT_MAX_CHARS = 280

# Markers that open the protected tail. The tail starts at the beginning of the line
# holding the earliest marker and is returned untouched.
COACH_MARKERS = ("📊 Strava AI Boost Coach", "Strava AI Boost Coach")
SIGNATURE_MARKER = "@Generated by Strava AI Boost"
CAMPUS_PREFIX = "📋"

_BLANK_LINE_RE = re.compile(r"\n[ \t\r\f\v]*\n\s*")
_SENTENCE_END_RE = re.compile(r"[.!?…]+")
_CLOSERS = set(")]»\"'’”")
_OPENERS = set("«\"(“[")


def _is_emoji_like(char: str) -> bool:
    """Pictographs and their combining helpers (variation selectors, ZWJ, skin tones)."""
    if char in ("\u200d", "\ufe0f", "\ufe0e"):
        return True
    return unicodedata.category(char) in ("So", "Sk")


def _split_protected_tail(description: str) -> tuple[str, str]:
    """Return (body, tail) where tail starts at the line of the first protected marker."""
    positions = [description.find(m) for m in (*COACH_MARKERS, SIGNATURE_MARKER)]
    positions = [p for p in positions if p >= 0]
    if not positions:
        return description, ""
    start = description.rfind("\n", 0, min(positions)) + 1
    return description[:start], description[start:]


def _boundaries(paragraph: str) -> list[int]:
    """Candidate split positions: index where the next sentence starts after whitespace.

    A boundary is sentence-ending punctuation, optionally followed by closing quotes
    and emojis that belong to the sentence ("plaisir ! 💪"), then whitespace, then a
    character that opens a sentence (uppercase letter, digit, opening quote). Requiring
    whitespace right after the punctuation is what keeps "4.5" or "5:36" whole, and
    requiring a sentence opener keeps "etc. et" or "... puis" together.
    """
    found = []
    n = len(paragraph)
    for match in _SENTENCE_END_RE.finditer(paragraph):
        end = match.end()
        while end < n and paragraph[end] in _CLOSERS:
            end += 1
        # Absorb emojis that close the sentence, possibly after spaces.
        while True:
            probe = end
            while probe < n and paragraph[probe] in " \t":
                probe += 1
            if probe < n and _is_emoji_like(paragraph[probe]):
                while probe < n and _is_emoji_like(paragraph[probe]):
                    probe += 1
                end = probe
                continue
            break
        start = end
        while start < n and paragraph[start].isspace():
            start += 1
        if start == end or start >= n:
            continue  # no whitespace after the sentence, or end of paragraph
        nxt = paragraph[start]
        if nxt.isupper() or nxt.isdigit() or nxt in _OPENERS:
            found.append(end)
    return found


def _split_paragraph(paragraph: str, max_chars: int) -> list[str]:
    """Split one single-line paragraph recursively at the boundary closest to the middle."""
    if len(paragraph) <= max_chars:
        return [paragraph]
    candidates = _boundaries(paragraph)
    if not candidates:
        return [paragraph]
    middle = len(paragraph) / 2
    cut = min(candidates, key=lambda pos: (abs(pos - middle), pos))
    left = paragraph[:cut].rstrip()
    right = paragraph[cut:].lstrip()
    if not left or not right:
        return [paragraph]
    return _split_paragraph(left, max_chars) + _split_paragraph(right, max_chars)


def _format_body(body: str, max_chars: int) -> list[str]:
    paragraphs = [p.strip() for p in _BLANK_LINE_RE.split(body.strip())]
    out: list[str] = []
    for paragraph in paragraphs:
        if not paragraph:
            continue
        if paragraph.startswith(CAMPUS_PREFIX) or "\n" in paragraph:
            # The Campus line keeps its exact place and shape; multi-line paragraphs
            # are structured content (lists, Campus line + text) and are left alone.
            out.append(paragraph)
            continue
        out.extend(_split_paragraph(paragraph, max_chars))
    return out


def format_paragraphs(description: str, max_chars: int = DEFAULT_MAX_CHARS) -> str:
    """Lay out a generated description in short paragraphs, changing only whitespace.

    Args:
        description: the generated description (may already hold the coach block and
            the signature).
        max_chars: maximum length of a body paragraph before it is split.

    Returns:
        The reformatted description. Empty or non-string input is returned unchanged.
    """
    if not isinstance(description, str) or not description.strip():
        return description
    body, tail = _split_protected_tail(description)
    paragraphs = _format_body(body, max_chars)
    formatted = "\n\n".join(paragraphs)
    if tail:
        return f"{formatted}\n\n{tail}" if formatted else tail
    return formatted
