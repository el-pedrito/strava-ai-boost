def get_recent_campus_sessions(activity_date: str = None) -> List[Dict[str, Any]]:
    """Get Campus Coach sessions for the current week only (max 6)"""
    try:
        logger.info("🔍 Querying Campus Coach sessions from DynamoDB...")
        table = dynamodb.Table(COACHING_SESSIONS_TABLE)
        
        from datetime import datetime, timedelta
        if activity_date:
            try:
                act_dt = datetime.fromisoformat(activity_date.replace('Z', '+00:00'))
            except Exception:
                act_dt = datetime.utcnow()
        else:
            act_dt = datetime.utcnow()
        
        # Get sessions updated in the last 14 days (covers current + previous week)
        cutoff_date = (act_dt - timedelta(days=14)).isoformat()
        
        logger.info(f"Filtering sessions: updated_at >= '{cutoff_date}', status = 'À faire'")
        
        response = table.scan(
            FilterExpression='updated_at >= :cutoff AND #status = :status',
            ExpressionAttributeNames={'#status': 'status'},
            ExpressionAttributeValues={
                ':cutoff': cutoff_date,
                ':status': 'À faire'
            }
        )
        
        sessions = response.get('Items', [])
        logger.info(f"📊 Found {len(sessions)} 'À faire' sessions updated since {cutoff_date}")
        
        # Sort by updated_at DESC to get most recent sessions first
        sessions = sorted(sessions, key=lambda x: x.get('updated_at', ''), reverse=True)
        
        # Cap at 6 (typical max sessions per week)
        sessions = sessions[:6]
        
        for session in sessions:
            logger.info(f"  - {session.get('title', 'Unknown')} (week {session.get('week_number', '?')}, updated: {session.get('updated_at', '?')})")
        
        from decimal import Decimal
        def decimal_to_float(obj):
            if isinstance(obj, Decimal):
                return float(obj)
            elif isinstance(obj, dict):
                return {k: decimal_to_float(v) for k, v in obj.items()}
            elif isinstance(obj, list):
                return [decimal_to_float(item) for item in obj]
            return obj
        
        sessions = decimal_to_float(sessions)
        
        logger.info(f"✅ Retrieved {len(sessions)} Campus Coach sessions for agent matching")
        return sessions
        
    except Exception as e:
        logger.error(f"❌ Failed to retrieve Campus Coach sessions: {str(e)}")
        return []


