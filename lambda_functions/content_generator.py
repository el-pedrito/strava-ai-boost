def _parse_pace_mmss(pace_str: str) -> float:
    """Convert mm:ss pace string to float minutes. E.g. '5:45' -> 5.75"""
    try:
        parts = str(pace_str).split(':')
        if len(parts) == 2:
            return int(parts[0]) + int(parts[1]) / 60.0
        return float(pace_str)
    except (ValueError, TypeError):
        return 0.0


def _classify_by_pace_zones(avg_pace: float, pace_std: float, pace_range: float,
                            pace_zones: Dict[str, Any]) -> Optional[Dict[str, str]]:
    """
    Classify workout by matching average pace against user-configured pace zones.
    Returns {'type': ..., 'label': ...} if a zone matches, None otherwise.
    Only used when pace variability is low (not intervals).
    """
    # Zone definitions: key -> (type_name, label_fr)
    zone_labels = {
        'recovery': ('recovery_run', 'Recup / Recovery'),
        'ef': ('steady_easy_run', 'Endurance Fondamentale'),
        'tempo': ('tempo', 'Tempo'),
        'sweet_spot': ('sweet_spot', 'Sweet Spot'),
        'seuil_60': ('threshold_60', 'Seuil 60'),
        'seuil_30': ('threshold_30', 'Seuil 30'),
        'allure_marathon': ('marathon_pace', 'Allure Marathon'),
        'allure_semi': ('half_marathon_pace', 'Allure Semi'),
        'interval': ('intervals', 'Intervalles / VMA'),
    }

    best_match = None
    best_distance = float('inf')

    for zone_key, zone_val in pace_zones.items():
        if not isinstance(zone_val, dict):
            continue
        zone_min = _parse_pace_mmss(zone_val.get('min', '0'))
        zone_max = _parse_pace_mmss(zone_val.get('max', '0'))
        if zone_min <= 0 or zone_max <= 0:
            continue

        # Ensure min <= max (min pace = fastest = lower number, max pace = slowest = higher number)
        slow_pace = max(zone_min, zone_max)
        fast_pace = min(zone_min, zone_max)

        if fast_pace <= avg_pace <= slow_pace:
            # Direct match — compute distance to zone midpoint
            midpoint = (fast_pace + slow_pace) / 2
            distance = abs(avg_pace - midpoint)
            if distance < best_distance:
                best_distance = distance
                type_name, label_fr = zone_labels.get(zone_key, (zone_key, zone_key.replace('_', ' ').title()))
                best_match = {'type': type_name, 'label': label_fr}

    if best_match:
        logger.info(f"Pace zone match: avg_pace={avg_pace:.2f} -> {best_match['label']}")
    return best_match


def classify_workout_from_streams(blocks: List[Dict[str, Any]],
                                  pace_zones: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """
    Classify the workout type based on pace variability across blocks.
    Uses user-configured pace zones when available, falls back to statistical heuristics.
    Filters warmup/cooldown outliers using IQR.
    Returns classification with type and stats for the agent.
    """
    all_paces = [b.get('pace_min_km', 0) for b in blocks if 0 < b.get('pace_min_km', 0) < 15]
    valid_hrs = [b.get('hr_bpm', 0) for b in blocks if b.get('hr_bpm', 0) > 0]

    if len(all_paces) < 3:
        return {'type': 'unknown', 'confidence': 0}

    # Filter outliers using IQR (removes warmup/cooldown/stop artifacts)
    sorted_paces = sorted(all_paces)
    q1_idx = len(sorted_paces) // 4
    q3_idx = 3 * len(sorted_paces) // 4
    q1 = sorted_paces[q1_idx]
    q3 = sorted_paces[q3_idx]
    iqr = q3 - q1
    lower_bound = q1 - 1.5 * iqr
    upper_bound = q3 + 1.5 * iqr
    core_paces = [p for p in all_paces if lower_bound <= p <= upper_bound]

    if len(core_paces) < 3:
        core_paces = all_paces  # fallback if too many filtered

    avg_pace = sum(core_paces) / len(core_paces)
    pace_std = (sum((p - avg_pace) ** 2 for p in core_paces) / len(core_paces)) ** 0.5
    pace_range = max(core_paces) - min(core_paces)
    avg_hr = sum(valid_hrs) / len(valid_hrs) if valid_hrs else 0
    hr_std = (sum((h - avg_hr) ** 2 for h in valid_hrs) / len(valid_hrs)) ** 0.5 if valid_hrs else 0

    # Step 1: Detect intervals by variability (regardless of pace zones)
    if pace_std > 0.6 and pace_range > 2.0:
        workout_type = 'intervals'
        label = 'Fractionne / Intervalles'
    elif pace_std > 0.40:
        # Check if it's a progression (pace decreasing over time)
        first_third = core_paces[:len(core_paces)//3]
        last_third = core_paces[-(len(core_paces)//3):]
        if first_third and last_third:
            avg_first = sum(first_third) / len(first_third)
            avg_last = sum(last_third) / len(last_third)
            if avg_first - avg_last > 0.5:
                workout_type = 'progression'
                label = 'Sortie progressive (negative split)'
            else:
                workout_type = 'steady_easy_run'
                label = 'Endurance fondamentale (allure legerement variable)'
        else:
            workout_type = 'steady_easy_run'
            label = 'Endurance fondamentale (allure legerement variable)'
    else:
        # Step 2: Steady effort — use pace zones if configured
        zone_match = _classify_by_pace_zones(avg_pace, pace_std, pace_range, pace_zones) if pace_zones else None

        if zone_match:
            workout_type = zone_match['type']
            label = zone_match['label']
        else:
            # Fallback: statistical heuristic
            if pace_std < 0.40:
                workout_type = 'steady_easy_run'
                label = 'Endurance fondamentale (allure reguliere)'
            else:
                workout_type = 'tempo'
                label = 'Tempo / Allure soutenue'

    classification = {
        'type': workout_type,
        'label': label,
        'avg_pace_min_km': round(avg_pace, 2),
        'pace_std_filtered': round(pace_std, 2),
        'pace_range_filtered': round(pace_range, 2),
        'blocks_total': len(all_paces),
        'blocks_core': len(core_paces),
        'avg_hr': round(avg_hr) if avg_hr else None,
        'hr_std': round(hr_std, 1) if hr_std else None,
        'pace_zones_used': pace_zones is not None,
    }

    logger.info(f"Workout classification: {workout_type} (std={pace_std:.2f}, range={pace_range:.2f}, core={len(core_paces)}/{len(all_paces)}, zones={'yes' if pace_zones else 'no'}) -> {label}")
    return classification


def detect_workout_phases(streams_compressed: Dict[str, Any]) -> List[Dict[str, Any]]:
    """
    Pre-compute workout phases from compressed blocks.
    Groups consecutive blocks with similar pace into phases (warmup, tempo, intervals, cooldown).
    Uses adaptive tolerance based on workout variability to avoid over-splitting steady runs.
    Returns a compact summary the agent can easily match against Campus Coach sessions.
    """
    if not streams_compressed:
        return []

    blocks = streams_compressed.get('blocks', [])
    if not blocks:
        return []

    # Compute pace variability with IQR filtering (same as classify_workout_from_streams)
    all_paces = [b.get('pace_min_km', 0) for b in blocks if 0 < b.get('pace_min_km', 0) < 15]
    if len(all_paces) < 3:
        return []

    sorted_paces = sorted(all_paces)
    q1 = sorted_paces[len(sorted_paces) // 4]
    q3 = sorted_paces[3 * len(sorted_paces) // 4]
    iqr = q3 - q1
    core_paces = [p for p in all_paces if (q1 - 1.5 * iqr) <= p <= (q3 + 1.5 * iqr)]
    if len(core_paces) < 3:
        core_paces = all_paces

    avg_core = sum(core_paces) / len(core_paces)
    pace_std = (sum((p - avg_core) ** 2 for p in core_paces) / len(core_paces)) ** 0.5

    # Adaptive tolerance: wider for steady runs, tighter for intervals
    # Steady run (std < 0.35): tolerance 1.0 min/km -> groups everything into ~1-3 phases
    # Intervals (std > 0.6): tolerance 0.3 min/km -> detects fast/slow alternation
    if pace_std < 0.35:
        tolerance = 1.0
    elif pace_std < 0.6:
        tolerance = 0.7
    else:
        tolerance = 0.3

    # Group consecutive blocks with similar pace
    phases = []
    current_phase = None

    for block in blocks:
        pace = block.get('pace_min_km', 0)
        hr = block.get('hr_bpm', 0)
        duration = block.get('duration_s', 30)

        if pace <= 0 or pace > 15:  # Skip stopped/invalid blocks
            continue

        if current_phase is None:
            current_phase = {'paces': [pace], 'hrs': [hr], 'duration_s': duration}
        elif abs(pace - (sum(current_phase['paces']) / len(current_phase['paces']))) < tolerance:
            # Same phase — similar pace within tolerance
            current_phase['paces'].append(pace)
            current_phase['hrs'].append(hr)
            current_phase['duration_s'] += duration
        else:
            # New phase — pace changed significantly
            phases.append(current_phase)
            current_phase = {'paces': [pace], 'hrs': [hr], 'duration_s': duration}

    if current_phase:
        phases.append(current_phase)

    # Summarize each phase
    summary = []
    for p in phases:
        avg_pace = sum(p['paces']) / len(p['paces'])
        avg_hr = sum(p['hrs']) / len(p['hrs']) if any(p['hrs']) else 0
        dur_min = p['duration_s'] / 60

        if dur_min < 0.5:  # Skip very short phases (<30s)
            continue

        pace_min = int(avg_pace)
        pace_sec = int((avg_pace - pace_min) * 60)

        summary.append({
            'duration_min': round(dur_min, 1),
            'avg_pace': f"{pace_min}:{pace_sec:02d}/km",
            'avg_hr': round(avg_hr) if avg_hr else None,
            'blocks_count': len(p['paces'])
        })

    logger.info(f"Detected {len(summary)} workout phases from {len(blocks)} blocks (tolerance={tolerance})")
    for s in summary:
        logger.info(f"  Phase: {s['duration_min']}min at {s['avg_pace']} (HR {s['avg_hr']})")

    return summary


def compress_streams_to_blocks(streams_data: Dict[str, Any], activity_data: Dict[str, Any], activity_id: str) -> Optional[Dict[str, Any]]:
    """
    Compress streams data into adaptive blocks based on activity duration
    
    This function:
    1. Checks if compressed data already exists in DynamoDB (cached)
    2. If not, compresses raw streams into adaptive blocks with avg pace/HR
    3. Adapts block duration based on activity length (less compression for short activities)
    4. Extracts key GPS points and reverse geocodes them to identify route landmarks
    5. Stores the compressed data in DynamoDB for future use
    6. Returns structured blocks ready for agent analysis
    
    Adaptive compression strategy (progressive):
    - < 60 min: 10s blocks (light compression, enables phase detection)
    - 60-120 min: 30s blocks (standard compression)
    - > 120 min: 30s blocks (standard compression)
    
    NO INTERPRETATION - just data compression. The agent will do the matching with Campus Coach.
    
    Args:
        streams_data: Raw streams from Strava (velocity_smooth, heartrate, time, distance, latlng)
        activity_data: Activity metadata for context
        activity_id: Activity ID for caching in DynamoDB
        
    Returns:
        Compressed streams as adaptive blocks + route landmarks, or None if no streams available
    """
    if not streams_data or not streams_data.get('velocity_smooth'):
        logger.info("No streams data available for compression")
        return None
    
    try:
        # Check if compressed data already exists in DynamoDB
        table = dynamodb.Table(ACTIVITIES_TABLE)
        response = table.get_item(Key={'activity_id': activity_id})
        
        if 'Item' in response and response['Item'].get('streams_analysis_json'):
            logger.info("✅ Using cached compressed streams from DynamoDB")
            cached_data = json.loads(response['Item']['streams_analysis_json'])
            return cached_data
        
        logger.info("No cached data found, compressing streams with adaptive blocks...")
        
        # Extract key streams
        velocity = streams_data.get('velocity_smooth', {}).get('data', [])
        heartrate = streams_data.get('heartrate', {}).get('data', [])
        time_series = streams_data.get('time', {}).get('data', [])
        distance = streams_data.get('distance', {}).get('data', [])
        latlng = streams_data.get('latlng', {}).get('data', [])  # GPS coordinates
        cadence_stream = streams_data.get('cadence', {}).get('data', [])
        watts_stream = streams_data.get('watts', {}).get('data', [])
        
        if not velocity or len(velocity) < 10:
            logger.info("Insufficient streams data for compression")
            return None
        
        # Calculate activity duration in minutes
        activity_duration_seconds = activity_data.get('elapsed_time', 0)
        activity_duration_minutes = activity_duration_seconds / 60
        
        # Adaptive block duration based on activity length
        # Strategy: Light compression for short activities (phase detection), standard for long
        if activity_duration_minutes < 60:
            block_duration = 10  # 10s blocks for short activities (enables workout phase detection)
            compression_level = "light"
            logger.info(f"Activity duration: {activity_duration_minutes:.1f} min → Light compression (10s blocks)")
        else:
            block_duration = 30  # 30s blocks for long activities
            compression_level = "standard"
        
        logger.info(f"Activity duration: {activity_duration_minutes:.1f} min → Block duration: {block_duration}s ({compression_level})")
        
        blocks = []
        
        i = 0
        while i < len(velocity):
            # Find all points in this 30s block
            start_time = time_series[i] if i < len(time_series) else i
            end_time = start_time + block_duration
            
            block_velocities = []
            block_hrs = []
            block_cadences = []
            block_watts = []
            block_end_idx = i
            
            # Collect all data points in this 30s window
            while block_end_idx < len(velocity):
                current_time = time_series[block_end_idx] if block_end_idx < len(time_series) else block_end_idx
                if current_time >= end_time:
                    break
                
                if velocity[block_end_idx] > 0:
                    block_velocities.append(velocity[block_end_idx])
                
                if block_end_idx < len(heartrate) and heartrate[block_end_idx]:
                    block_hrs.append(heartrate[block_end_idx])

                if block_end_idx < len(cadence_stream) and cadence_stream[block_end_idx]:
                    block_cadences.append(cadence_stream[block_end_idx])

                if block_end_idx < len(watts_stream) and watts_stream[block_end_idx]:
                    block_watts.append(watts_stream[block_end_idx])

                block_end_idx += 1
            
            # Calculate averages for this block
            if block_velocities:
                avg_velocity = sum(block_velocities) / len(block_velocities)
                avg_pace_min_km = 1000 / (avg_velocity * 60) if avg_velocity > 0 else 0
                avg_speed_kmh = avg_velocity * 3.6
                
                block = {
                    'time_min': round(start_time / 60, 1),
                    'duration_s': block_duration,
                    'pace_min_km': round(avg_pace_min_km, 2),
                    'speed_kmh': round(avg_speed_kmh, 1)
                }
                
                if block_hrs:
                    block['hr_bpm'] = int(sum(block_hrs) / len(block_hrs))

                if block_cadences:
                    block['cadence'] = int(sum(block_cadences) / len(block_cadences))

                if block_watts:
                    block['watts'] = int(sum(block_watts) / len(block_watts))

                blocks.append(block)
            
            # Move to next block
            i = block_end_idx if block_end_idx > i else i + 1
        
        # Extract route landmarks from Strava segments (no reverse geocoding)
        route_landmarks = []
        
        # Use Strava segment_efforts (reliable, free, already has city names)
        segment_efforts = activity_data.get('segment_efforts', [])
        if segment_efforts and len(segment_efforts) > 0:
            logger.info(f"Extracting route landmarks from {len(segment_efforts)} Strava segments...")
            
            # Sample key segments: start, middle, end
            # Sort by start_index to get chronological order
            sorted_segments = sorted(segment_efforts, key=lambda s: s.get('start_index', 0))
            
            # Select key segments (start, middle, end)
            key_indices = []
            if len(sorted_segments) >= 3:
                key_indices = [0, len(sorted_segments) // 2, len(sorted_segments) - 1]
            elif len(sorted_segments) == 2:
                key_indices = [0, 1]
            else:
                key_indices = [0]
            
            for idx in key_indices:
                segment_effort = sorted_segments[idx]
                segment = segment_effort.get('segment', {})
                
                segment_name = segment.get('name')
                city = segment.get('city')
                country = segment.get('country')
                
                if city or segment_name:
                    # Calculate position in activity
                    position = 'start' if idx == 0 else 'end' if idx == len(key_indices) - 1 else 'middle'
                    
                    landmark = {
                        'position': position,
                        'segment_name': segment_name,
                        'city': city,
                        'country': country,
                        'distance_m': segment_effort.get('distance', 0),
                        'elapsed_time_s': segment_effort.get('elapsed_time', 0),
                        'pr_rank': segment_effort.get('pr_rank'),
                    }
                    route_landmarks.append(landmark)
                    
                    logger.info(f"   ✅ Landmark at {position}: {segment_name} ({city}, {country})")
            
            logger.info(f"✅ Identified {len(route_landmarks)} route landmarks from Strava segments")
        else:
            logger.info("No Strava segments available for route landmarks")

        # Extract segment PRs (top 3 personal performances across ALL segments)
        segment_prs = []
        for se in segment_efforts:
            pr_rank = se.get('pr_rank')
            if pr_rank and pr_rank <= 3:
                segment_prs.append({
                    'name': se.get('segment', {}).get('name', ''),
                    'pr_rank': pr_rank,
                    'elapsed_time_s': se.get('elapsed_time', 0),
                    'distance_m': se.get('distance', 0),
                })

        # Build performance_summary from streams (more granular than Strava activity averages)
        performance_summary = {}
        if heartrate:
            performance_summary['avg_hr_bpm'] = int(sum(heartrate) / len(heartrate))
            performance_summary['max_hr_bpm'] = max(heartrate)
        if velocity:
            non_zero_vel = [v for v in velocity if v > 0]
            if non_zero_vel:
                avg_vel = sum(non_zero_vel) / len(non_zero_vel)
                performance_summary['avg_speed_kmh'] = round(avg_vel * 3.6, 1)
                performance_summary['max_speed_kmh'] = round(max(non_zero_vel) * 3.6, 1)
                performance_summary['avg_pace_min_km'] = round(1000 / (avg_vel * 60), 2) if avg_vel > 0 else None
        if cadence_stream:
            non_zero_cad = [c for c in cadence_stream if c > 0]
            if non_zero_cad:
                performance_summary['avg_cadence'] = int(sum(non_zero_cad) / len(non_zero_cad))
                performance_summary['max_cadence'] = max(non_zero_cad)
        if watts_stream:
            non_zero_watts = [w for w in watts_stream if w > 0]
            if non_zero_watts:
                performance_summary['avg_watts'] = int(sum(non_zero_watts) / len(non_zero_watts))
                performance_summary['max_watts'] = max(non_zero_watts)
        # Add Strava-provided scalar metrics
        for key in ('workout_type', 'suffer_score', 'pr_count', 'achievement_count'):
            val = activity_data.get(key)
            if val is not None:
                performance_summary[key] = val

        # Create compressed data structure
        compressed_data = {
            'blocks': blocks,
            'block_duration_s': block_duration,
            'compression_level': compression_level,
            'activity_duration_min': round(activity_duration_minutes, 1),
            'total_blocks': len(blocks),
            'total_duration_min': round(blocks[-1]['time_min'] if blocks else 0, 1),
            'compression_ratio': f"{len(velocity)} points → {len(blocks)} blocks ({block_duration}s blocks)",
            'route_landmarks': route_landmarks if route_landmarks else None,
            'performance_summary': performance_summary if performance_summary else None,
            'segment_prs': segment_prs if segment_prs else None
        }
        
        # Store compressed data in DynamoDB for future use
        table.update_item(
            Key={'activity_id': activity_id},
            UpdateExpression="SET streams_analysis_json = :data, updated_at = :updated",
            ExpressionAttributeValues={
                ':data': json.dumps(compressed_data),
                ':updated': datetime.utcnow().isoformat()
            }
        )
        
        logger.info(f"✅ Streams compressed and cached in DynamoDB")
        logger.info(f"   Compression: {len(velocity)} points → {len(blocks)} blocks ({block_duration}s each)")
        logger.info(f"   Total duration: {compressed_data['total_duration_min']:.1f} minutes")
        logger.info(f"   Route landmarks: {len(route_landmarks)} identified")
        logger.info(f"   Data size reduction: ~{100 * (1 - len(blocks) / len(velocity)):.0f}%")
        
        return compressed_data
        
    except Exception as e:
        logger.error(f"Failed to compress streams: {str(e)}")
        logger.error(f"   This is not critical - will proceed without compressed streams")
        return None


def extract_enduraw_report(activity_data: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    """
    Extract Enduraw Report from activity description
    
    Enduraw adds a report to the description after 2 minutes:
    📈 𝗠𝘆 𝗘𝗻𝗱𝘂𝗿𝗮𝘄 𝗥𝗲𝗽𝗼𝗿𝘁 📈
    🏢 You climbed 53 floors today!
    Adjusted Pace: 𝟱:𝟯𝟮/km
    🏝️ Elevation (0.4% avg) cost you 𝟬'𝟬𝟰"/km.
    🌬️ Wind (17.2km/h) cost you 𝟬'𝟭𝟱"/km.
    ...
    """
    try:
        description = activity_data.get('description', '')
        
        if not description or '𝗘𝗻𝗱𝘂𝗿𝗮𝘄 𝗥𝗲𝗽𝗼𝗿𝘁' not in description:
            return None
        
        # Extract the Enduraw Report section
        import re
        
        # Find the Enduraw Report block
        enduraw_pattern = r'📈 𝗠𝘆 𝗘𝗻𝗱𝘂𝗿𝗮𝘄 𝗥𝗲𝗽𝗼𝗿𝘁 📈(.*?)(?:Try it now|$)'
        match = re.search(enduraw_pattern, description, re.DOTALL)
        
        if not match:
            return None
        
        report_text = match.group(1).strip()
        
        # Parse key metrics from report
        enduraw_data = {
            'report_available': True,
            'report_text': report_text,
            'metrics': {}
        }
        
        # Extract adjusted pace
        pace_match = re.search(r'Adjusted Pace:\s*([𝟬-𝟵]+):([𝟬-𝟵]+)/km', report_text)
        if pace_match:
            # Convert bold numbers to regular
            min_bold = pace_match.group(1).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            sec_bold = pace_match.group(2).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            enduraw_data['metrics']['adjusted_pace'] = f"{min_bold}:{sec_bold}/km"
        
        # Extract wind impact
        wind_match = re.search(r'Wind \(([0-9.]+)km/h\) cost you ([𝟬-𝟵]+)\'([𝟬-𝟵]+)"/km', report_text)
        if wind_match:
            wind_speed = wind_match.group(1)
            min_bold = wind_match.group(2).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            sec_bold = wind_match.group(3).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            enduraw_data['metrics']['wind_speed'] = f"{wind_speed}km/h"
            enduraw_data['metrics']['wind_cost'] = f"{min_bold}'{sec_bold}\"/km"
        
        # Extract elevation impact
        elev_match = re.search(r'Elevation \(([0-9.]+)% avg\) cost you ([𝟬-𝟵]+)\'([𝟬-𝟵]+)"/km', report_text)
        if elev_match:
            elev_pct = elev_match.group(1)
            min_bold = elev_match.group(2).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            sec_bold = elev_match.group(3).translate(str.maketrans('𝟬𝟭𝟮𝟯𝟰𝟱𝟲𝟳𝟴𝟵', '0123456789'))
            enduraw_data['metrics']['elevation_avg'] = f"{elev_pct}%"
            enduraw_data['metrics']['elevation_cost'] = f"{min_bold}'{sec_bold}\"/km"
        
        logger.info(f"Extracted Enduraw Report: {enduraw_data['metrics']}")
        return enduraw_data
        
    except Exception as e:
        logger.error(f"Failed to extract Enduraw Report: {str(e)}")
        return None


def retrieve_activity_data_from_dynamodb(activity_id: str) -> Optional[Dict[str, Any]]:
    """
    Retrieve complete activity data from DynamoDB
    
    This retrieves all data stored by ActivityFetcher to avoid Step Functions payload limits
    """
    try:
        table = dynamodb.Table(ACTIVITIES_TABLE)
        
        response = table.get_item(Key={'activity_id': activity_id})
        
        if 'Item' not in response:
            logger.error(f"Activity {activity_id} not found in DynamoDB")
            return None
        
        item = response['Item']
        
        # Parse JSON strings back to dictionaries
        activity_data = json.loads(item.get('activity_data_json', '{}'))
        # For long activities, streams are already compressed in DynamoDB
        streams_compressed = json.loads(item.get('streams_compressed_json', 'null')) if item.get('streams_compressed_json') else None
        athlete_stats = json.loads(item.get('athlete_stats_json', 'null')) if item.get('athlete_stats_json') else None
        athlete_profile = json.loads(item.get('athlete_profile_json', 'null')) if item.get('athlete_profile_json') else None
        gear_details = json.loads(item.get('gear_details_json', 'null')) if item.get('gear_details_json') else None
        intervals_icu_data = json.loads(item.get('intervals_icu_json', 'null')) if item.get('intervals_icu_json') else None

        # CRITICAL FIX: Convert numeric string values back to numbers
        # JSON serialization converts Decimal to string, we need to convert back
        def convert_numeric_strings(obj):
            """Recursively convert numeric strings to float/int"""
            if isinstance(obj, dict):
                return {k: convert_numeric_strings(v) for k, v in obj.items()}
            elif isinstance(obj, list):
                return [convert_numeric_strings(item) for item in obj]
            elif isinstance(obj, str):
                # Try to convert string to number if it looks numeric
                try:
                    # Check if it's an integer
                    if '.' not in obj and 'e' not in obj.lower():
                        return int(obj)
                    else:
                        return float(obj)
                except (ValueError, AttributeError):
                    return obj
            return obj
        
        # Apply conversion to all data
        activity_data = convert_numeric_strings(activity_data)
        streams_compressed = convert_numeric_strings(streams_compressed) if streams_compressed else None
        athlete_stats = convert_numeric_strings(athlete_stats) if athlete_stats else None
        athlete_profile = convert_numeric_strings(athlete_profile) if athlete_profile else None
        gear_details = convert_numeric_strings(gear_details) if gear_details else None
        intervals_icu_data = convert_numeric_strings(intervals_icu_data) if intervals_icu_data else None

        logger.info(f"Retrieved activity data from DynamoDB for {activity_id}")

        return {
            'activity_data': activity_data,
            'streams_compressed': streams_compressed,  # Pre-compressed from DynamoDB
            'athlete_stats': athlete_stats,
            'athlete_profile': athlete_profile,
            'gear_details': gear_details,
            'intervals_icu_data': intervals_icu_data
        }
        
    except Exception as e:
        logger.error(f"Failed to retrieve activity data from DynamoDB: {str(e)}")
        return None


